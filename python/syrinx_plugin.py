"""
syrinx_plugin — write a Syrinx plugin in a few lines of Python (protocol version 1, see docs/protocol.md).

Standard library only, Python 3.10+. One file: copy it next to your plugin, or install the kit with pip.

    from syrinx_plugin import Plugin, track

    plugin = Plugin("org.example.tones", "Tones", "1.0.0", description="Pure tones, for testing")

    @plugin.catalog("notes", "Notes", type="track")
    def notes(req, skip, limit):
        return [track("a4", "A4", subtitle="440 Hz", playable=True)]

    @plugin.stream
    def stream(req, id, quality):
        return {"url": f"audio/{id}.wav"}

    plugin.serve(port=8700)          # then add http://<this machine>:8700/manifest.json in Syrinx

What the SDK does for you:
  - builds manifest.json from what you registered (resources, catalogs, permissions);
  - routes every protocol URL to your function, with the parameters already read and checked;
  - answers JSON in UTF-8, errors as {"error": "..."} with the right status, CORS for the web app;
  - serves files and generated bytes with Range support (seeking in a track);
  - optional account token in the path (prefix="/u/<account>"), handed to you as req.account.

Two ways to run it: plugin.serve() (a small threaded HTTP server, enough at home) or plugin.wsgi, a WSGI application
for gunicorn, uWSGI, waitress… behind a reverse proxy with HTTPS.
"""
from __future__ import annotations

import json
import mimetypes
import os
import re
import urllib.parse
from dataclasses import dataclass, field
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from typing import Any, Callable

__all__ = ["Plugin", "Request", "Raw", "PluginError", "NotFound", "track", "album", "artist", "playlist", "section"]
__version__ = "1.0.0"

PROTOCOL = 1
TYPES = ("track", "album", "artist", "playlist")
QUALITIES = ("raw", "opus256", "opus128", "mp3320")
PERMISSIONS = ("plays", "devices", "voice", "files", "notifications", "update")


# ===================================================================== items

def _item(type_: str, id: str, title: str, **fields: Any) -> dict:
    """An item: id, type, title, plus any optional field of the protocol (None values are dropped)."""
    out = {"id": str(id), "type": type_, "title": str(title)}
    out.update({k: v for k, v in fields.items() if v is not None})
    return out


def track(id: str, title: str, **fields: Any) -> dict:
    """A track. Common fields: subtitle, artist, album, artistId, albumId, duration (s), artwork, playable,
    favorite (leave it out for items that cannot be liked), live, explicit, badge, notice, source."""
    return _item("track", id, title, **fields)


def album(id: str, title: str, **fields: Any) -> dict:
    """An album. Common fields: artist, artistId, year, genre, songCount, artwork, description."""
    return _item("album", id, title, **fields)


def artist(id: str, title: str, **fields: Any) -> dict:
    """An artist. Common fields: artwork, banner, description."""
    return _item("artist", id, title, **fields)


def playlist(id: str, title: str, **fields: Any) -> dict:
    """A playlist. subtitle usually says how many tracks."""
    return _item("playlist", id, title, **fields)


def section(id: str, title: str, items: list[dict] | None = None, load: str | None = None) -> dict:
    """A search section: its items right away, or a `load` URL (relative to the manifest) the app calls next."""
    out: dict = {"id": id, "title": title}
    if load is not None:
        out["load"] = load
    else:
        out["items"] = items or []
    return out


# ===================================================================== requests and responses

class PluginError(Exception):
    """Raise it anywhere in a handler: the app shows `message` as is. 503 means "not ready, try later"."""

    def __init__(self, message: str, status: int = 400) -> None:
        super().__init__(message)
        self.message = message
        self.status = status


class NotFound(PluginError):
    def __init__(self, message: str = "Not found") -> None:
        super().__init__(message, 404)


@dataclass
class Request:
    method: str
    path: str                       # relative to the manifest folder, e.g. "catalog/top.json"
    query: dict[str, str]
    headers: dict[str, str]         # lower-case names
    body: bytes = b""
    account: str | None = None      # token from the path, when the plugin has prefix="/u/<account>"
    params: dict[str, str] = field(default_factory=dict)   # from a route pattern, e.g. "audio/<id>.wav"

    @property
    def lang(self) -> str:
        """Interface language of the app ("fr", "en"…): answer in it when you can."""
        return (self.query.get("lang") or self.headers.get("x-syrinx-lang") or "en").split("-")[0].lower()

    def json(self) -> Any:
        try:
            return json.loads(self.body.decode("utf-8") or "null")
        except ValueError:
            raise PluginError("Body is not JSON") from None

    def int(self, name: str, default: int, lo: int | None = None, hi: int | None = None) -> int:
        try:
            v = int(self.query.get(name, default))
        except ValueError:
            raise PluginError(f"{name} must be a number") from None
        if lo is not None:
            v = max(lo, v)
        if hi is not None:
            v = min(hi, v)
        return v


class Raw:
    """A non-JSON answer: audio, images, a page. Ranges (seeking) are handled for you.
    Give either `body` (bytes) or `path` (a file on disk, streamed in chunks)."""

    def __init__(self, body: bytes | None = None, content_type: str | None = None, *, path: str | None = None,
                 status: int = 200, headers: dict[str, str] | None = None) -> None:
        if (body is None) == (path is None):
            raise ValueError("Raw needs body or path")
        self.body, self.path, self.status = body, path, status
        self.content_type = content_type or (mimetypes.guess_type(path)[0] if path else None) or "application/octet-stream"
        self.headers = headers or {}

    def size(self) -> int:
        return len(self.body) if self.body is not None else os.path.getsize(self.path)

    def chunks(self, start: int, end: int, step: int = 64 * 1024):
        if self.body is not None:
            for i in range(start, end + 1, step):
                yield self.body[i:min(i + step, end + 1)]
            return
        with open(self.path, "rb") as f:
            f.seek(start)
            left = end - start + 1
            while left > 0:
                b = f.read(min(step, left))
                if not b:
                    break
                left -= len(b)
                yield b


_RANGE = re.compile(r"bytes=(\d*)-(\d*)$")


def _range(raw: Raw, header: str | None) -> tuple[int, int, int, int] | None:
    """(status, start, end, size), or None when the range cannot be served (416)."""
    size = raw.size()
    m = _RANGE.match(header or "")
    if raw.status != 200 or not m or size == 0:
        return raw.status, 0, size - 1, size
    a, b = m.groups()
    if a == "":                                  # the last N bytes
        n = int(b or 0)
        start, end = max(0, size - n), size - 1
    else:
        start, end = int(a), min(int(b) if b else size - 1, size - 1)
    if start > end or start >= size:
        return None
    return 206, start, end, size


# ===================================================================== the plugin

Handler = Callable[..., Any]


class Plugin:
    """A Syrinx plugin. Register handlers with the decorators, then serve() or mount wsgi."""

    def __init__(self, id: str, name: str, version: str, *, description: str | None = None,
                 color: str | None = None, permissions: list[str] | None = None, prefix: str = "") -> None:
        self.id, self.name, self.version = id, name, version
        self.description, self.color = description, color
        self.permissions = list(permissions or [])
        unknown = set(self.permissions) - set(PERMISSIONS)
        if unknown:
            raise ValueError(f"unknown permissions: {', '.join(sorted(unknown))}")
        # "/u/<account>" → the token in the path is handed to handlers as req.account
        self.prefix = prefix.rstrip("/")
        self._catalogs: list[dict] = []
        self._catalog_fns: dict[str, Handler] = {}
        self._resources: list[str] = []
        self._routes: list[tuple[str, re.Pattern, Handler]] = []
        self._fns: dict[str, Handler] = {}
        self._import: dict | None = None
        self._manifest_hook: Callable[[Request, dict], None] | None = None

    # ------------------------------------------------------------------ registration

    def _declare(self, resource: str) -> None:
        if resource not in self._resources:
            self._resources.append(resource)

    def catalog(self, id: str, name: str, *, type: str = "track", section: str = "home"):
        """A home row (section="home") or a library tab ("library"). fn(req, skip, limit) -> list of items."""
        if type not in TYPES or section not in ("home", "library"):
            raise ValueError("catalog type must be track/album/artist/playlist, section home/library")

        def deco(fn: Handler) -> Handler:
            self._declare("catalog")
            self._catalogs.append({"id": id, "name": name, "type": type, "section": section})
            self._catalog_fns[id] = fn
            return fn
        return deco

    def search(self, fn: Handler) -> Handler:
        """fn(req, q, source) -> list of sections, or a plain list of items (shown as one section).
        `source` is None, or a word the user asked for by voice ("on <source>")."""
        self._declare("search")
        self._fns["search"] = fn
        return fn

    def meta(self, fn: Handler) -> Handler:
        """fn(req, type, id) -> {"item": ..., "tracks": [...], ...}, or None for 404."""
        self._declare("meta")
        self._fns["meta"] = fn
        return fn

    def stream(self, fn: Handler) -> Handler:
        """fn(req, id, quality) -> {"url": ..., "live"?, "noStore"?, "cacheKey"?, "headers"?}, or None for 404."""
        self._declare("stream")
        self._fns["stream"] = fn
        return fn

    def similar(self, fn: Handler) -> Handler:
        """fn(req, id, limit, exclude: set, context: list) -> list of tracks. id may be "random" or "wave"."""
        self._declare("similar")
        self._fns["similar"] = fn
        return fn

    def lyrics(self, fn: Handler) -> Handler:
        """fn(req, title, artist, album, duration) -> {"synced", "lines": [{"t", "text"}]}."""
        self._declare("lyrics")
        self._fns["lyrics"] = fn
        return fn

    def actions(self, list_fn: Handler):
        """list_fn(req, type, id) -> list of actions. Then register what each one does with @plugin.action(id)."""
        self._declare("actions")
        self._fns["actions"] = list_fn
        return list_fn

    def action(self, id: str):
        """fn(req, context: dict, values: dict) -> {"ok", "message", "refresh"?, "favorite"?, ...}."""
        def deco(fn: Handler) -> Handler:
            self._fns[f"action:{id}"] = fn
            return fn
        return deco

    def settings(self, groups: Handler, save: Handler, reset: Handler | None = None) -> None:
        """Settings described by the plugin (protocol 4.13).
        groups(req) -> list of groups; save(req, group_id, values) -> {"ok", "message", "refresh"?};
        reset(req, group_id) -> same shape. Raise PluginError for an unknown group."""
        self._declare("settings")
        self._fns["settings"], self._fns["settings:save"] = groups, save
        if reset:
            self._fns["settings:reset"] = reset

    def importer(self, label: str, hint: str, preview: Handler) -> None:
        """Add from a link. preview(req, url) -> {"item", "stats", "sample", "action"}; the action is a normal
        @plugin.action. Raise PluginError("This link is not supported") for links you do not take."""
        self._declare("import")
        self._import = {"label": label, "hint": hint}
        self._fns["import"] = preview

    def resource(self, name: str) -> None:
        """Declare a resource you serve yourself with @plugin.route (companions: stats, scrobble…)."""
        self._declare(name)

    def route(self, method: str, pattern: str, resource: str | None = None):
        """Any other URL, relative to the manifest. Patterns take <name> parts: "audio/<id>.wav".
        fn(req) -> a dict/list (JSON), a Raw, or None (204). `resource` also declares it in the manifest."""
        rx = re.compile("^" + re.sub(r"<(\w+)>", r"(?P<\1>[^/]+)", re.escape(pattern).replace(r"\<", "<").replace(r"\>", ">")) + "$")

        def deco(fn: Handler) -> Handler:
            if resource:
                self._declare(resource)
            self._routes.append((method.upper(), rx, fn))
            return fn
        return deco

    def on_manifest(self, fn: Callable[[Request, dict], None]) -> Callable[[Request, dict], None]:
        """fn(req, manifest) may change the manifest per call: translate names, hide a row until a setting is done."""
        self._manifest_hook = fn
        return fn

    # ------------------------------------------------------------------ manifest

    def manifest(self, req: Request) -> dict:
        m: dict = {"protocol": PROTOCOL, "id": self.id, "name": self.name, "version": self.version}
        if self.description:
            m["description"] = self.description
        if self.color:
            m["color"] = self.color
        m["resources"] = list(self._resources)
        if self._catalogs:
            m["catalogs"] = [dict(c) for c in self._catalogs]
        if self._import:
            m["import"] = dict(self._import)
        m["permissions"] = list(self.permissions)
        if self._manifest_hook:
            self._manifest_hook(req, m)
        return m

    # ------------------------------------------------------------------ dispatch

    def handle(self, req: Request) -> tuple[int, Any]:
        """(status, body) for a request whose path is already relative to the manifest folder."""
        try:
            return self._dispatch(req)
        except PluginError as e:
            return e.status, {"error": e.message}

    def _dispatch(self, req: Request) -> tuple[int, Any]:
        p, m, f = req.path, req.method, self._fns

        for method, rx, fn in self._routes:          # your own routes first: they may override anything
            hit = rx.match(p)
            if hit and method == m:
                req.params = hit.groupdict()
                out = fn(req)
                return (204, None) if out is None else (200, out)

        if m == "GET" and p == "manifest.json":
            return 200, self.manifest(req)

        if m == "GET" and (hit := re.fullmatch(r"catalog/(.+)\.json", p)):
            fn = self._catalog_fns.get(hit[1])
            if not fn:
                raise NotFound("Unknown catalog")
            skip, limit = req.int("skip", 0, 0), req.int("limit", 50, 1, 500)
            return 200, {"items": list(fn(req, skip, limit) or [])[:limit]}

        if m == "GET" and p == "search.json" and "search" in f:
            q = req.query.get("q", "").strip()
            if not q:
                return 200, {"sections": []}
            out = f["search"](req, q, req.query.get("source") or None) or []
            if out and isinstance(out[0], dict) and "type" in out[0]:      # a plain list of items
                out = [section("results", self.name, out)]
            return 200, {"sections": out}

        if m == "GET" and (hit := re.fullmatch(r"meta/(track|album|artist|playlist)/(.+)\.json", p)) and "meta" in f:
            out = f["meta"](req, hit[1], hit[2])
            if out is None:
                raise NotFound()
            return 200, out

        if m == "GET" and (hit := re.fullmatch(r"stream/(.+)\.json", p)) and "stream" in f:
            quality = req.query.get("quality", "raw")
            out = f["stream"](req, hit[1], quality if quality in QUALITIES else "raw")
            if out is None:
                raise NotFound("Track unavailable")
            return 200, out

        if m == "GET" and (hit := re.fullmatch(r"similar/(.+)\.json", p)) and "similar" in f:
            ids = lambda k: [x for x in req.query.get(k, "").split(",") if x]
            out = f["similar"](req, hit[1], req.int("limit", 15, 1, 50), set(ids("exclude")), ids("context"))
            return 200, {"items": list(out or [])}

        if m == "GET" and p == "lyrics.json" and "lyrics" in f:
            q = req.query
            out = f["lyrics"](req, q.get("title", ""), q.get("artist", ""), q.get("album", ""),
                              float(q["duration"]) if q.get("duration") else None)
            return 200, out or {"synced": False, "lines": []}

        if m == "GET" and (hit := re.fullmatch(r"actions/(track|album|artist|playlist)/(.+)\.json", p)) and "actions" in f:
            return 200, {"actions": list(f["actions"](req, hit[1], hit[2]) or [])}

        if m == "POST" and (hit := re.fullmatch(r"action/(.+)", p)):
            fn = f.get(f"action:{hit[1]}")
            if not fn:
                raise NotFound("Unknown action")
            body = req.json() or {}
            return 200, fn(req, body.get("context") or {}, body.get("values") or {})

        if m == "GET" and p == "import/preview.json" and "import" in f:
            url = req.query.get("url", "").strip()
            if not url:
                raise PluginError("Missing link")
            return 200, f["import"](req, url)

        if p == "settings.json" and m == "GET" and "settings" in f:
            return 200, {"groups": list(f["settings"](req) or [])}
        if (hit := re.fullmatch(r"settings/([\w.-]+)", p)) and "settings" in f:
            if m == "POST":
                body = req.json() or {}
                return 200, f["settings:save"](req, hit[1], body.get("values") or {})
            if m == "DELETE" and "settings:reset" in f:
                return 200, f["settings:reset"](req, hit[1])

        raise NotFound()

    # ------------------------------------------------------------------ HTTP plumbing (shared by both servers)

    def _split(self, raw_path: str) -> tuple[str, str | None] | None:
        """Path relative to the manifest folder, and the account token, or None when outside the plugin."""
        path = urllib.parse.unquote(raw_path)
        prefix = self.prefix
        account = None
        if "<account>" in prefix:
            rx = "^" + re.escape(prefix).replace(re.escape("<account>"), r"(?P<account>[^/]+)") + "/"
            hit = re.match(rx, path)
            if not hit:
                return None
            account, path = hit["account"], path[hit.end():]
        elif prefix:
            if not path.startswith(prefix + "/"):
                return None
            path = path[len(prefix) + 1:]
        else:
            path = path.lstrip("/")
        return path, account

    def _respond(self, method: str, raw_path: str, query: str, headers: dict[str, str], body: bytes):
        """(status, headers, iterable of bytes) for any request."""
        cors = {"Access-Control-Allow-Origin": "*",
                "Access-Control-Allow-Headers": "Content-Type, X-Syrinx-Lang, X-Filename, Range",
                "Access-Control-Allow-Methods": "GET, POST, DELETE, OPTIONS",
                "Access-Control-Expose-Headers": "Content-Range, Content-Length, Accept-Ranges"}
        if method == "OPTIONS":
            return 204, cors, []
        split = self._split(raw_path)
        if split is None:
            status, out = 404, {"error": "Not found"}
            req = None
        else:
            q = {k: v[-1] for k, v in urllib.parse.parse_qs(query, keep_blank_values=True).items()}
            req = Request(method, split[0], q, headers, body, split[1])
            try:
                status, out = self.handle(req)
            except Exception as e:                  # a bug in a handler: say so without leaking details
                import traceback
                traceback.print_exc()
                status, out = 500, {"error": f"Plugin error ({type(e).__name__})"}

        if isinstance(out, Raw):
            rng = _range(out, headers.get("range"))
            if rng is None:
                return 416, {**cors, "Content-Range": f"bytes */{out.size()}"}, []
            st, start, end, size = rng
            h = {**cors, **out.headers, "Content-Type": out.content_type, "Accept-Ranges": "bytes",
                 "Content-Length": str(max(0, end - start + 1))}
            if st == 206:
                h["Content-Range"] = f"bytes {start}-{end}/{size}"
            return st, h, ([] if method == "HEAD" else out.chunks(start, end))
        if status == 204:
            return 204, cors, []
        data = json.dumps(out, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
        h = {**cors, "Content-Type": "application/json; charset=utf-8", "Content-Length": str(len(data)),
             "Cache-Control": "no-store"}
        return status, h, [data]

    # ------------------------------------------------------------------ servers

    def wsgi(self, environ: dict, start_response: Callable) -> Any:
        """WSGI application: gunicorn 'myplugin:plugin.wsgi'."""
        headers = {k[5:].replace("_", "-").lower(): v for k, v in environ.items() if k.startswith("HTTP_")}
        if environ.get("CONTENT_TYPE"):
            headers["content-type"] = environ["CONTENT_TYPE"]
        length = int(environ.get("CONTENT_LENGTH") or 0)
        body = environ["wsgi.input"].read(length) if length else b""
        method = environ["REQUEST_METHOD"]
        status, h, chunks = self._respond(method, environ.get("SCRIPT_NAME", "") + environ.get("PATH_INFO", ""),
                                          environ.get("QUERY_STRING", ""), headers, body)
        reasons = {200: "OK", 204: "No Content", 206: "Partial Content", 400: "Bad Request", 404: "Not Found",
                   416: "Range Not Satisfiable", 500: "Internal Server Error", 503: "Service Unavailable"}
        start_response(f"{status} {reasons.get(status, 'Status')}", list(h.items()))
        return chunks

    def serve(self, host: str = "0.0.0.0", port: int = 8700, *, quiet: bool = False) -> None:
        """Small threaded HTTP server. For the internet, put it behind a reverse proxy with HTTPS."""
        server = self.http_server(host, port, quiet=quiet)
        where = f"http://{'localhost' if host in ('0.0.0.0', '') else host}:{server.server_address[1]}"
        print(f"{self.name} {self.version}: {where}{self.prefix.replace('<account>', '<token>')}/manifest.json")
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            pass

    def http_server(self, host: str = "0.0.0.0", port: int = 8700, *, quiet: bool = True) -> ThreadingHTTPServer:
        """The server serve() runs, not started yet (port=0 picks a free port; tests use this)."""
        plugin = self

        class H(BaseHTTPRequestHandler):
            protocol_version = "HTTP/1.1"

            def _go(self) -> None:
                url = urllib.parse.urlsplit(self.path)
                length = int(self.headers.get("Content-Length") or 0)
                body = self.rfile.read(length) if length else b""
                headers = {k.lower(): v for k, v in self.headers.items()}
                status, h, chunks = plugin._respond(self.command, url.path, url.query, headers, body)
                self.send_response(status)
                for k, v in h.items():
                    self.send_header(k, v)
                if "Content-Length" not in h:
                    self.send_header("Content-Length", "0")
                self.end_headers()
                if self.command == "HEAD":
                    return
                try:
                    for c in chunks:
                        self.wfile.write(c)
                except (BrokenPipeError, ConnectionResetError):
                    pass                         # the player stopped reading (seek, next track)

            do_GET = do_POST = do_DELETE = do_OPTIONS = do_HEAD = _go

            def log_message(self, fmt: str, *args: Any) -> None:
                if not quiet:
                    super().log_message(fmt, *args)

        ThreadingHTTPServer.daemon_threads = True
        return ThreadingHTTPServer((host, port), H)
